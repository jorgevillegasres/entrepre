// Initialize sample data in localStorage
export const initializeSampleData = () => {
  const hasData = localStorage.getItem('saas_products');

  if (!hasData) {
    localStorage.setItem('saas_products', JSON.stringify(sampleProducts));
    localStorage.setItem('saas_customers', JSON.stringify(sampleCustomers));
    localStorage.setItem('saas_sales', JSON.stringify(sampleSales));
    localStorage.setItem('saas_transactions', JSON.stringify(sampleTransactions));
    localStorage.setItem('saas_stock_movements', JSON.stringify([]));
    localStorage.setItem('saas_notifications', JSON.stringify([]));

    console.log('✅ Sample data initialized');
  }
};
